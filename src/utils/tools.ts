/**
 * 判断值是否为空。
 */
export function isEmpty(value: unknown): value is null | undefined | '' {
  if (value === null || value === undefined) {
    return true;
  }
  if (typeof value === 'string' && value.trim() === '') {
    return true;
  }
  if (Array.isArray(value) && value.length === 0) {
    return true;
  }
  return false;
}
